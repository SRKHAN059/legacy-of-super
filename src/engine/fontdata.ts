/** Height of a glyph cell including descenders. */
export const GLYPH_H = 9;
/** Pixels between glyphs. */
export const GLYPH_SPACING = 1;
/** Default line advance. */
export const LINE_H = 10;

/** Advance width of a single character. Unknown characters render as '?'. */
export function charWidth(ch: string): number {
  const g = GLYPHS[ch] ?? GLYPHS['?'];
  return g[0].length + GLYPH_SPACING;
}

/** Pixel width of a string on one line. */
export function measure(text: string): number {
  let w = 0;
  for (const ch of text) w += charWidth(ch);
  return w > 0 ? w - GLYPH_SPACING : 0;
}

/** Greedy word wrap to a pixel width. Honours explicit '\n'. */
export function wrap(text: string, maxW: number): string[] {
  const out: string[] = [];
  for (const para of text.split('\n')) {
    const words = para.split(' ');
    let line = '';
    for (const word of words) {
      const cand = line ? `${line} ${word}` : word;
      if (measure(cand) <= maxW || !line) {
        line = cand;
      } else {
        out.push(line);
        line = word;
      }
    }
    out.push(line);
  }
  return out;
}
